-- ---------- compositions ----------
create table if not exists public.compositions (
  id bigint generated by default as identity primary key,
  map_id bigint not null references public.maps(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 100),
  notes text,
  is_main boolean not null default false,
  status text not null default 'active'
    check (status in ('active', 'draft', 'discarded')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (map_id, name)
);

create unique index if not exists compositions_one_main_per_map
on public.compositions(map_id)
where is_main = true;

create table if not exists public.composition_slots (
  composition_id bigint not null references public.compositions(id) on delete cascade,
  slot smallint not null check (slot between 1 and 5),
  player_id bigint references public.players(id) on delete set null,
  agent_id bigint references public.agents(id) on delete set null,
  primary key (composition_id, slot)
);

create or replace function public.normalize_composition_status()
returns trigger
language plpgsql
as $$
begin
  if new.status <> 'active' then
    new.is_main := false;
  end if;
  return new;
end;
$$;

drop trigger if exists compositions_normalize_status on public.compositions;
create trigger compositions_normalize_status
before insert or update of status, is_main on public.compositions
for each row execute function public.normalize_composition_status();

create or replace function public.save_composition(
  p_id bigint,
  p_map_id bigint,
  p_name text,
  p_notes text,
  p_is_main boolean,
  p_slots jsonb
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_slot jsonb;
begin
  if not public.is_current_admin() then
    raise exception 'Solo un administrador puede guardar composiciones';
  end if;

  if p_is_main then
    update public.compositions
    set is_main = false
    where map_id = p_map_id and (p_id is null or id <> p_id);
  end if;

  if p_id is null then
    insert into public.compositions(map_id, name, notes, is_main)
    values (p_map_id, trim(p_name), p_notes, p_is_main)
    returning id into v_id;
  else
    update public.compositions
    set map_id = p_map_id,
        name = trim(p_name),
        notes = p_notes,
        is_main = p_is_main,
        updated_at = now()
    where id = p_id
    returning id into v_id;
    if v_id is null then raise exception 'La composición no existe'; end if;
  end if;

  delete from public.composition_slots where composition_id = v_id;
  for v_slot in select * from jsonb_array_elements(coalesce(p_slots, '[]'::jsonb))
  loop
    insert into public.composition_slots(composition_id, slot, player_id, agent_id)
    values (
      v_id,
      (v_slot->>'slot')::smallint,
      nullif(v_slot->>'player_id', '')::bigint,
      nullif(v_slot->>'agent_id', '')::bigint
    );
  end loop;
  return v_id;
end;
$$;

