do $$
declare
  t text;
begin
  foreach t in array array[
    'players', 'agents', 'maps', 'player_agents', 'compositions',
    'composition_slots', 'calendar_events'
  ]
  loop
    execute format('drop policy if exists public_read on public.%I', t);
    execute format('create policy public_read on public.%I for select using (true)', t);
    execute format('drop policy if exists admin_manage on public.%I', t);
    execute format(
      'create policy admin_manage on public.%I for all to authenticated '
      'using (public.is_current_admin()) with check (public.is_current_admin())', t
    );
  end loop;
end $$;

