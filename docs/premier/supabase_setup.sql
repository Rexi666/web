create or replace function public.open_attendance_poll(
  p_title text,
  p_map_id bigint,
  p_source_event_id bigint,
  p_options jsonb
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_poll_id bigint;
  v_item jsonb;
begin
  if not public.is_current_admin() then
    raise exception 'Solo un administrador puede abrir votaciones';
  end if;
  if jsonb_array_length(coalesce(p_options, '[]'::jsonb)) = 0 then
    raise exception 'La votación necesita al menos una fecha';
  end if;

  insert into public.attendance_polls(title, map_id, source_event_id, created_by)
  values (trim(p_title), p_map_id, p_source_event_id, auth.uid())
  returning id into v_poll_id;

  for v_item in select * from jsonb_array_elements(p_options)
  loop
    insert into public.attendance_options(poll_id, event_date, event_time, sort_order)
    values (
      v_poll_id,
      (v_item->>'date')::date,
      nullif(v_item->>'time', '')::time,
      coalesce((v_item->>'sort_order')::integer, 0)
    );
  end loop;
  return v_poll_id;
end;
$$;

create or replace function public.vote_attendance(
  p_option_id bigint,
  p_choice text
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_poll_id bigint;
  v_player_id bigint;
begin
  if p_choice not in ('available', 'maybe', 'unavailable') then
    raise exception 'Opción de voto no válida';
  end if;

  select o.poll_id into v_poll_id
  from public.attendance_options o
  join public.attendance_polls p on p.id = o.poll_id
  where o.id = p_option_id and p.status = 'open';
  if v_poll_id is null then raise exception 'La votación está cerrada'; end if;

  select id into v_player_id
  from public.players
  where user_id = auth.uid();
  if v_player_id is null then
    raise exception 'Tu cuenta no está vinculada a un jugador';
  end if;

  insert into public.attendance_votes(poll_id, option_id, player_id, choice, updated_at)
  values (v_poll_id, p_option_id, v_player_id, p_choice, now())
  on conflict (option_id, player_id)
  do update set choice = excluded.choice, updated_at = now();
end;
$$;

create or replace function public.close_attendance_poll(
  p_poll_id bigint,
  p_selected_option_id bigint
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_poll public.attendance_polls%rowtype;
  v_option public.attendance_options%rowtype;
  v_event_id bigint;
begin
  if not public.is_current_admin() then
    raise exception 'Solo un administrador puede cerrar votaciones';
  end if;

  select * into v_poll
  from public.attendance_polls
  where id = p_poll_id and status = 'open'
  for update;
  if v_poll.id is null then raise exception 'La votación no está abierta'; end if;

  select * into v_option
  from public.attendance_options
  where id = p_selected_option_id and poll_id = p_poll_id;
  if v_option.id is null then
    raise exception 'La fecha elegida no pertenece a la votación';
  end if;

  insert into public.calendar_events(
    type, title, map_id, start_date, event_time, notes, occurrences
  ) values (
    'play_day', v_poll.title, v_poll.map_id, v_option.event_date,
    v_option.event_time, 'Fecha seleccionada mediante votación de asistencia',
    '[]'::jsonb
  ) returning id into v_event_id;

  update public.attendance_polls
  set status = 'closed',
      selected_option_id = v_option.id,
      closed_at = now()
  where id = p_poll_id;
  return v_event_id;
end;
$$;

-- ---------- matches and statistics ----------
create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  match_type text not null check (match_type in ('premier', 'ranked')),
  calendar_event_id bigint references public.calendar_events(id) on delete set null,
  played_at date not null,
  result text not null,
  team_score smallint not null check (team_score between 0 and 99),
  opponent_score smallint not null check (opponent_score between 0 and 99),
  map_id bigint not null references public.maps(id) on delete restrict,
  composition_id bigint references public.compositions(id) on delete set null,
  notes text,
  result_image_url text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint matches_result_check check (
    result in ('win', 'loss')
    or (match_type = 'ranked' and result = 'draw')
  ),
  constraint matches_premier_event check (
    (match_type = 'premier' and calendar_event_id is not null)
    or (match_type = 'ranked' and calendar_event_id is null)
  )
);

create table if not exists public.match_player_stats (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  agent_id bigint not null references public.agents(id) on delete restrict,
  acs smallint not null default 0 check (acs >= 0),
  kills smallint not null default 0 check (kills >= 0),
  deaths smallint not null default 0 check (deaths >= 0),
  assists smallint not null default 0 check (assists >= 0),
  first_bloods smallint not null default 0 check (first_bloods >= 0),
  trades smallint not null default 0 check (trades >= 0),
  plants smallint not null default 0 check (plants >= 0),
  defuses smallint not null default 0 check (defuses >= 0),
  unique (match_id, player_id)
);

